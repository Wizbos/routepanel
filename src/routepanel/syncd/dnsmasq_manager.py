# src/routepanel/syncd/dnsmasq_manager.py
import subprocess, json, os, tempfile, shutil, logging
from routepanel.domainval import filter_valid_domains

log = logging.getLogger("routesyncd")

def render_fragment(rules: list[dict]) -> str:
    """Build dnsmasq `ipset=` lines mapping each rule's domains -> its rule_<id>
    set:
        ipset=/youtube.com/googlevideo.com/rule_5
    EXIT-INDEPENDENT -- the set name is the same regardless of which exit the rule
    currently uses, so this fragment changes only when a rule's domains change,
    never on failover. dnsmasq matches a domain and all its subdomains, capturing
    the real per-session CDN hostnames that apex resolution would miss.

    Domains are re-validated here (not just at rule-creation time in the panel
    API) and anything that wouldn't parse as a plain hostname is dropped and
    logged -- defense in depth for rows written before validation existed, or
    inserted directly into the DB outside the API. One bad domain in a rule
    can never corrupt the `ipset=/.../` line for the whole rule, and can never
    poison the rest of the fragment (see the 2026-07-09 incident)."""
    lines = ["# generated by routepanel -- do not edit by hand"]
    for r in rules:
        raw = json.loads(r["domains"])
        domains = filter_valid_domains(
            raw,
            on_invalid=lambda d, rid=r["id"]: log.warning(
                "dnsmasq fragment: skipping invalid domain %r in rule %s", d, rid),
        )
        if not domains:
            continue
        joined = "/".join(domains)
        lines.append(f"ipset=/{joined}/rule_{r['id']}")
    return "\n".join(lines) + "\n"

def write_fragment(path: str, content: str) -> bool:
    """Atomically write the fragment. Returns True iff content changed."""
    old = ""
    if os.path.exists(path):
        with open(path) as f:
            old = f.read()
    if old == content:
        return False
    d = os.path.dirname(path) or "."
    fd, tmp = tempfile.mkstemp(dir=d)
    with os.fdopen(fd, "w") as f:
        f.write(content)
    os.replace(tmp, path)
    return True

def reload_dnsmasq(service: str = "dnsmasq") -> None:
    subprocess.run(["systemctl", "reload", service], capture_output=True)

def check_config() -> bool:
    """Syntax-check the assembled dnsmasq config exactly as dnsmasq would load
    it at start/reload: `dnsmasq --test` reads the default config-dir
    (`/etc/dnsmasq.d/`), which includes our `routepanel-base.conf`, whose
    `conf-file=` directive pulls in the fragment this module just wrote --
    so a malformed fragment is caught here, not by a crashed/refused-to-start
    dnsmasq. This is the plain-dnsmasq equivalent of `pihole-FTL dnsmasq-test`
    (verified live to return rc=0/rc!=0 correctly on Pi-hole v5.18 and v6.4 in
    the corp deployment that hit the 2026-07-09 incident); `--test` is
    documented to do the same syntax validation for stock dnsmasq."""
    r = subprocess.run(["dnsmasq", "--test"], capture_output=True)
    return r.returncode == 0

def sync_fragment(path: str, service: str, rules: list[dict]) -> bool:
    """Render + write + validate + reload (only if changed).

    Hardened against the 2026-07-09 outage class (an unvalidated fragment
    reached a downstream resolver and it refused to (re)start, killing site
    DNS for 20 minutes): before installing changed content we snapshot the
    currently-applied (presumed-good) fragment to `path + ".lkg"`. After
    installing the new content, `check_config()` validates the assembled
    config. If validation fails we restore the last-known-good snapshot (or
    remove the fragment if there wasn't one yet -- never leave a known-bad
    file in place), log the rejection, and skip the reload entirely, so a bad
    rule save can never reach a running dnsmasq. Returns True if reloaded."""
    content = render_fragment(rules)
    existed = os.path.exists(path)
    if existed:
        with open(path) as f:
            if f.read() == content:
                return False   # unchanged -- nothing to validate/reload

    lkg = path + ".lkg"
    if existed:
        shutil.copy2(path, lkg)

    write_fragment(path, content)

    if not check_config():
        if os.path.exists(lkg):
            shutil.copy2(lkg, path)
            log.error("REJECTED invalid dnsmasq fragment from panel (dnsmasq --test "
                      "failed), kept last-known-good: %s", path)
        else:
            try:
                os.remove(path)
            except FileNotFoundError:
                pass
            log.error("REJECTED invalid dnsmasq fragment from panel (dnsmasq --test "
                      "failed), no prior good fragment -- removed: %s", path)
        return False

    reload_dnsmasq(service)
    log.info("applied updated routed-domain forward fragment: %s", path)
    return True
